package com.example.questionbank.domain.model;

import com.example.questionbank.domain.exception.DomainException;

/**
 * Academic competency evaluated by one or more questions.
 */
public class Competency {

    private Long id;
    private final String name;
    private final String description;

    /**
     * Creates a competency.
     *
     * @param id identity assigned by the repository, or {@code null}
     * @param name unique competency name
     * @param description optional description
     */
    public Competency(Long id, String name, String description) {
        if (name == null || name.isBlank()) {
            throw new DomainException("The competency name is required");
        }
        this.id = id;
        this.name = name.trim();
        this.description = description == null ? null : description.trim();
    }

    /**
     * Assigns the identity generated by the persistence layer.
     *
     * @param id generated identity
     */
    public void assignIdentity(Long id) {
        this.id = id;
    }

    /** @return identity assigned by the repository, or {@code null} */
    public Long getId() {
        return id;
    }

    /** @return competency name */
    public String getName() {
        return name;
    }

    /** @return optional description */
    public String getDescription() {
        return description;
    }
}
