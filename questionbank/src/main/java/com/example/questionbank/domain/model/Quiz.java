package com.example.questionbank.domain.model;

import com.example.questionbank.domain.exception.DomainException;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;

/**
 * Quiz or simulation built from published questions.
 */
public class Quiz {

    private Long id;
    private final String title;
    private final Long createdById;
    private final List<Long> questionIds;
    private final LocalDateTime createdAt;

    /**
     * Creates or rehydrates a quiz.
     *
     * @param id identity assigned by the repository, or {@code null}
     * @param title quiz title
     * @param createdById identity of the user that created the quiz
     * @param questionIds identities of the included questions
     * @param createdAt creation timestamp, defaults to now when {@code null}
     */
    public Quiz(Long id, String title, Long createdById, Collection<Long> questionIds, LocalDateTime createdAt) {
        if (title == null || title.isBlank()) {
            throw new DomainException("The quiz title is required");
        }
        if (createdById == null) {
            throw new DomainException("The quiz creator is required");
        }
        if (questionIds == null || questionIds.isEmpty()) {
            throw new DomainException("A quiz must contain at least one question");
        }
        this.id = id;
        this.title = title.trim();
        this.createdById = createdById;
        this.questionIds = new ArrayList<>(questionIds);
        this.createdAt = createdAt == null ? LocalDateTime.now() : createdAt;
    }

    /**
     * Creates a quiz from fully loaded questions, rejecting any question that
     * is not {@link QuestionStatus#PUBLISHED}.
     *
     * <p>The rule is enforced before the quiz is handed to the repository, so a
     * failed validation leaves nothing persisted.</p>
     *
     * @param title quiz title
     * @param createdById identity of the user that creates the quiz
     * @param questions questions selected by the teacher
     * @return a new quiz in memory
     * @throws DomainException when a question is not published
     */
    public static Quiz create(String title, Long createdById, List<Question> questions) {
        if (questions == null || questions.isEmpty()) {
            throw new DomainException("A quiz must contain at least one question");
        }
        for (Question question : questions) {
            if (!question.isPublished()) {
                throw new DomainException("Question " + question.getId() + " is in status "
                        + question.getStatus() + "; only PUBLISHED questions can be added to a quiz");
            }
        }
        return new Quiz(null, title, createdById,
                questions.stream().map(Question::getId).toList(), LocalDateTime.now());
    }

    /**
     * Assigns the identity generated by the persistence layer.
     *
     * @param id generated identity
     */
    public void assignIdentity(Long id) {
        this.id = id;
    }

    /** @return identity assigned by the repository, or {@code null} */
    public Long getId() {
        return id;
    }

    /** @return quiz title */
    public String getTitle() {
        return title;
    }

    /** @return identity of the creator */
    public Long getCreatedById() {
        return createdById;
    }

    /** @return identities of the included questions */
    public List<Long> getQuestionIds() {
        return List.copyOf(questionIds);
    }

    /** @return creation timestamp */
    public LocalDateTime getCreatedAt() {
        return createdAt;
    }
}
