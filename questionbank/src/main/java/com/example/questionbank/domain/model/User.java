package com.example.questionbank.domain.model;

import com.example.questionbank.domain.exception.DomainException;

/**
 * Person that interacts with the question bank.
 */
public class User {

    private Long id;
    private final String fullName;
    private final String email;
    private final Role role;

    /**
     * Creates a user.
     *
     * @param id identity assigned by the repository, or {@code null}
     * @param fullName full name
     * @param email unique email address
     * @param role role in the system
     */
    public User(Long id, String fullName, String email, Role role) {
        if (fullName == null || fullName.isBlank()) {
            throw new DomainException("The user full name is required");
        }
        if (email == null || email.isBlank()) {
            throw new DomainException("The user email is required");
        }
        if (role == null) {
            throw new DomainException("The user role is required");
        }
        this.id = id;
        this.fullName = fullName.trim();
        this.email = email.trim();
        this.role = role;
    }

    /**
     * Assigns the identity generated by the persistence layer.
     *
     * @param id generated identity
     */
    public void assignIdentity(Long id) {
        this.id = id;
    }

    /** @return identity assigned by the repository, or {@code null} */
    public Long getId() {
        return id;
    }

    /** @return full name */
    public String getFullName() {
        return fullName;
    }

    /** @return email address */
    public String getEmail() {
        return email;
    }

    /** @return role in the system */
    public Role getRole() {
        return role;
    }
}
